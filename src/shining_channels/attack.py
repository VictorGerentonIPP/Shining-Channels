HW_SBOX = np.array([bin(v).count("1") for v in SBOX], dtype=np.float64)


def cpa_correlations(traces, plaintexts, byte, chunk=1000):
    cpa = Cpa(nc=256, kind=Cpa.Xor, use_64bit=True)
    x = plaintexts[:, [byte]].astype(np.uint16)
    for start in range(0, len(traces), chunk):
        stop = start + chunk
        cpa.fit_u(np.asarray(traces[start:stop], dtype=np.int16), x[start:stop])
    model = np.broadcast_to(HW_SBOX[None, :, None], (1, 256, traces.shape[1])).copy()
    return cpa.get_correlation(model)[0]


def snr(traces, plaintexts, key, byte, chunk=1000):
    metric = SNR(nc=256, use_64bit=True)
    classes = (SBOX[plaintexts[:, byte] ^ key[byte]]).astype(np.uint16)[:, None]
    for start in range(0, len(traces), chunk):
        stop = start + chunk
        metric.fit_u(np.asarray(traces[start:stop], dtype=np.int16), classes[start:stop])
    return np.nan_to_num(metric.get_snr()[0])


def leakage_window(traces, plaintexts, key, half_width=10):
    samples = set()
    for byte in range(16):
        peak = np.nanargmax(np.abs(cpa_correlations(traces, plaintexts, byte))[key[byte]])
        samples.update(range(max(0, peak - half_width), min(traces.shape[1], peak + half_width + 1)))
    return np.array(sorted(samples))


def log2_key_rank(traces, plaintexts, key, model):
    cpa = Cpa(nc=256, kind=Cpa.Xor, use_64bit=True)
    cpa.fit_u(traces, plaintexts.astype(np.uint16))
    correlations = np.abs(cpa.get_correlation(model))
    scores = np.nanmax(np.where(np.isfinite(correlations), correlations, np.nan), axis=2)
    costs = -np.log(np.clip(scores, 1e-12, 1.0))
    _, rank, _ = rank_nbin(costs, key.astype(np.int64), 1 << 16, method="hist")
    return math.log2(max(1.0, rank))


def key_rank_curve(traces, plaintexts, key, trace_counts, experiments, seed=0, locate=True):
    window = leakage_window(traces, plaintexts, key) if locate else np.arange(traces.shape[1])
    traces = np.ascontiguousarray(traces[:, window]).astype(np.int16)
    model = np.broadcast_to(HW_SBOX[None, :, None], (16, 256, len(window))).copy()
    rng = np.random.default_rng(seed)
    ranks = np.zeros((len(trace_counts), experiments))
    for i, count in enumerate(trace_counts):
        for j in range(experiments):
            subset = rng.choice(len(traces), count, replace=False)
            ranks[i, j] = log2_key_rank(traces[subset], plaintexts[subset], key, model)
        print(f"{count} traces: {ranks[i].mean():.1f} bits", flush=True)
    return ranks
